import jinja2
import markdown as md
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from importer import import_page, import_post, split_front_matter  # noqa: E402
import validate  # noqa: E402

REQUIRED_SECTIONS = [
    "What changed",
    "Why it matters",
    "What you can probably ignore",
    "Why it earned this rating",
    "What I'm watching next",
]
PAGES = ["about", "how-the-ratings-work", "privacy"]
LM_BOX = (
    '<aside class="lm-top" aria-label="Free fridge checklist"><p><strong>Free: the family '
    "AI-safety fridge checklist.</strong> One printable page for the whole family. Subscribe and it "
    'lands in your inbox right away.</p><a class="btn btn-sm" href="#subscribe">Send me the checklist</a></aside>'
)


# ---------------------------------------------------------------- helpers

def esc(value) -> str:
    return html.escape(str(value), quote=True)


def long_date(d: dt.date) -> str:
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def as_date(value) -> dt.date:
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    return dt.date.fromisoformat(str(value)[:10])


def render_body(body: str, suffix: str) -> str:
    if suffix == ".md":
        return md.markdown(body, extensions=["extra", "sane_lists"], output_format="html")
    return body.strip()


def display_body(body: str, suffix: str) -> str:
    """Source body -> the HTML that appears on the post page (minus the checklist box)."""
    return mark_bunker_check(autolink(render_body(body, suffix)))


def band_for(bands: list[dict], rating: int | None) -> dict | None:
    if rating is None:
        return None
    for b in bands:
        if b["low"] <= rating <= b["high"]:
            return b
    raise ValueError(f"rating {rating} is not on the 0-10 scale")


def insert_before_second_h2(body: str, snippet: str) -> str:
    hits = [m.start() for m in re.finditer(r"<h2[\s>]", body)]
    if len(hits) < 2:
        return body
    i = hits[1]
    return body[:i] + snippet + "\n" + body[i:]


def absolute_urls(fragment: str, base: str) -> str:
    return re.sub(r'(href|src)="/(?!/)', rf'\1="{base}/', fragment)


URL = re.compile(r"https?://[^\s<>\"']+")


def autolink(fragment: str) -> str:
    """Make bare URLs (as in the Sources list) clickable. Leaves existing links alone."""
    out, inside_a = [], 0
    for part in re.split(r"(<[^>]+>)", fragment):
        if part.startswith("<"):
            if re.match(r"<a[\s>]", part):
                inside_a += 1
            elif part.startswith("</a"):
                inside_a = max(0, inside_a - 1)
            out.append(part)
        elif inside_a:
            out.append(part)
        else:
            def link(m):
                url = m.group(0)
                trail = ""
                while url and url[-1] in ".,;:)":
                    trail = url[-1] + trail
                    url = url[:-1]
                return f'<a href="{url}" rel="noopener">{url}</a>{trail}'
            out.append(URL.sub(link, part))
    return "".join(out)


def mark_bunker_check(fragment: str) -> str:
    return re.sub(r"<blockquote>(\s*<p><strong>Bunker Check</strong></p>)",
                  r'<blockquote class="bunker-check">\1', fragment)


def section(fragment: str, heading: str) -> str:
    m = re.search(rf"<h2[^>]*>\s*{re.escape(heading)}\s*</h2>([\s\S]*?)(?=<h2[\s>]|$)", fragment)
    return m.group(1) if m else ""


def plain(fragment: str) -> str:
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", fragment))).strip()


def ignore_items(body: str) -> list[dict]:
    """The bolded "headline claims" from a post's What-you-can-probably-ignore section."""
    items = []
    for para in re.findall(r"<p>([\s\S]*?)</p>", section(body, "What you can probably ignore")):
        m = re.match(r"\s*<strong>([\s\S]*?)</strong>([\s\S]*)", para)
        if not m:
            continue
        claim = plain(m.group(1))
        if not claim or claim[0] not in "\"“":
            continue
        why = re.sub(r"\s*\[\d+\]", "", plain(m.group(2)))
        items.append({"claim": claim.strip("\"“”").rstrip("."), "why": why})
    return items


def direction(body: str) -> str | None:
    m = re.search(r"<strong>Direction:</strong>\s*([^<]+)", body)
    return m.group(1).strip().rstrip(".") if m else None


def needle_deg(value: float) -> float:
    # the gauge runs from 0 (far left) to 10 (far right), about 16.4 degrees per point
    return round((value - 5) * 16.36, 2)


def write(path: Path, text: str, changed: list[str], dry: bool) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return
    changed.append(str(path.relative_to(ROOT)))
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


# ---------------------------------------------------------------- loading

def load_site() -> dict:
    site = yaml.safe_load((ROOT / "site.yml").read_text(encoding="utf-8"))
    site["url"] = site["url"].rstrip("/")
    return site


def load_posts(site: dict) -> list[dict]:
    posts = []
    for path in sorted((ROOT / "content" / "posts").glob("*")):
        if path.suffix not in (".md", ".html"):
            continue
        meta, body = split_front_matter(path.read_text(encoding="utf-8"))
        if meta.get("draft"):
            continue
        slug = str(meta.get("slug") or path.stem)
        rating = meta.get("rating")
        rating = None if rating in (None, "") else int(rating)
        date = as_date(meta["date"])
        updated = as_date(meta["updated"]) if meta.get("updated") else None
        body_html = display_body(body, path.suffix)
        history = []
        for h in meta.get("rating_history") or []:
            hd = as_date(h["date"])
            r = int(h["rating"])
            history.append({"date": hd.isoformat(), "date_long": long_date(hd), "rating": r,
                            "band": band_for(site["bands"], r), "note": str(h.get("note", ""))})
        history.sort(key=lambda h: h["date"])
        if history and (updated is None or as_date(history[-1]["date"]) > updated):
            updated = as_date(history[-1]["date"])
        post = {
            "source": path,
            "slug": slug,
            "path": f"/posts/{slug}/",
            "url": f"{site['url']}/posts/{slug}/",
            "title": str(meta["title"]),
            "description": str(meta.get("description", "")),
            "date": date.isoformat(),
            "date_obj": date,
            "date_long": long_date(date),
            "updated": (updated or date).isoformat(),
            "order": int(meta.get("order") or 0),
            "rating": rating,
            "band": band_for(site["bands"], rating),
            "kicker": meta.get("type") or meta.get("kicker"),
            "author": meta.get("author") or site["author"],
            "updated_long": long_date(updated) if updated and updated != date else None,
            "meta": meta,
            "body_raw": body,
            "body_html": body_html,
            "history": history,
            "direction": direction(body_html),
            "ignore": ignore_items(body_html),
        }
        posts.append(post)
    # newest first; same day: higher `order` first, then title
    posts.sort(key=lambda p: p["title"])
    posts.sort(key=lambda p: (p["date"], p["order"]), reverse=True)
    return posts


def load_pages() -> dict[str, dict]:
    pages = {}
    for name in PAGES:
        path = ROOT / "content" / "pages" / f"{name}.html"
        meta, body = split_front_matter(path.read_text(encoding="utf-8"))
        meta["name"] = name
        meta["path"] = f"/{name}/"
        meta["body_html"] = render_body(body, path.suffix)
        pages[name] = meta
    return pages


# ---------------------------------------------------------------- safety net

def changed_since(rev: str) -> set[str]:
    out = subprocess.run(
        ["git", "diff", "--name-only", f"{rev}..HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout
    return {line.strip() for line in out.splitlines() if line.strip()}


def adopt_stray_html(reimport_from: str | None) -> list[str]:
    """Pull in posts and pages that were published as raw HTML instead of source."""
    notes = []
    changed = changed_since(reimport_from) if reimport_from else set()
    for page_dir in sorted((ROOT / "posts").iterdir()):
        html_file = page_dir / "index.html"
        if not html_file.is_file():
            continue
        slug = page_dir.name
        has_source = any((ROOT / "content" / "posts").glob(f"{slug}.*"))
        if not has_source:
            import_post(ROOT, slug)
            notes.append(f"imported new post published as HTML: {slug}")
            continue
        rel = f"posts/{slug}/index.html"
        source_touched = any(c.startswith(f"content/posts/{slug}.") for c in changed)
        if rel in changed and not source_touched:
            if import_post(ROOT, slug, overwrite=True, render=display_body):
                notes.append(f"re-imported post edited as HTML: {slug}")
    for name in PAGES:
        rel = f"{name}/index.html"
        if rel in changed and f"content/pages/{name}.html" not in changed:
            before = (ROOT / "content" / "pages" / f"{name}.html").read_text(encoding="utf-8")
            import_page(ROOT, name)
            after = (ROOT / "content" / "pages" / f"{name}.html").read_text(encoding="utf-8")
            if before != after:
                notes.append(f"re-imported page edited as HTML: {name}")
    return notes


# ---------------------------------------------------------------- rendering

def make_env(site: dict) -> jinja2.Environment:
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(ROOT / "templates"),
        autoescape=False,
        keep_trailing_newline=True,
        trim_blocks=False,
    )
    env.filters["esc"] = esc
    env.filters["tojson_compact"] = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))
    env.globals["gauge_arcs"] = (ROOT / "templates" / "_gauge_arcs.svg").read_text(encoding="utf-8").strip()
    return env


def crumbs(site, *items):
    out = [{"@type": "ListItem", "position": 1, "name": "Home", "item": f"{site['url']}/"}]
    for i, (name, url) in enumerate(items, start=2):
        out.append({"@type": "ListItem", "position": i, "name": name, "item": url})
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": out}


def build(site: dict, posts: list[dict], pages: dict, dry: bool) -> list[str]:
    env = make_env(site)
    changed: list[str] = []
    css = (ROOT / "assets" / "style.css").read_bytes()
    common = {
        "site": site,
        "posts": posts,
        "rated": [p for p in posts if p["rating"] is not None],
        "css_version": hashlib.sha256(css).hexdigest()[:8],
        "year": dt.date.today().year,
        "show_header_tagline": False,
        "main_nav": [("posts", "/posts/", "Posts"), ("ratings", "/ratings/", "Ratings"),
                     ("scale", "/how-the-ratings-work/", "The Scale"), ("about", "/about/", "About")],
        "footer_nav": [("/posts/", "Posts"), ("/ratings/", "Ratings"), ("/ignore/", "What to ignore"),
                       ("/how-the-ratings-work/", "The Scale"), ("/about/", "About"), ("/privacy/", "Privacy"),
                       ("/rss.xml", "RSS")],
        "reading": current_reading(site),
        # newest first, one claim per post so the homepage doesn't show three from one story
        "ignore_feed": [{**p["ignore"][0], "post": p} for p in posts if p["ignore"]],
    }
    url = site["url"]

    def render(template, out, **ctx):
        text = env.get_template(template).render(**common, **ctx)
        write(ROOT / out, text, changed, dry)

    # homepage
    render(
        "home.html", "index.html", nav="", has_subscribe=True,
        head={
            "title": site["name"], "description": site["description"], "canonical": f"{url}/",
            "og_title": site["name"], "og_url": f"{url}/",
            "jsonld": [
                {"@context": "https://schema.org", "@type": "WebSite", "name": site["name"], "url": f"{url}/",
                 "description": site["description"],
                 "publisher": {"@type": "Organization", "name": site["name"], "url": f"{url}/",
                               "logo": {"@type": "ImageObject", "url": f"{url}/assets/icon-512.png"}, "email": site["email"]}},
                {"@context": "https://schema.org", "@type": "Organization", "name": site["name"], "url": f"{url}/",
                 "logo": f"{url}/assets/icon-512.png", "email": site["email"], "slogan": site["tagline"]},
            ],
        },
    )

    # posts
    for i, post in enumerate(posts):
        body = insert_before_second_h2(post["body_html"], LM_BOX)
        render(
            "post.html", f"posts/{post['slug']}/index.html", nav="posts", has_subscribe=True,
            post={**post, "body_html": body},
            newer=posts[i - 1] if i > 0 else None,
            older=posts[i + 1] if i + 1 < len(posts) else None,
            head={
                "title": f"{post['title']} | {site['name']}", "description": post["description"],
                "canonical": post["url"], "og_type": "article", "og_title": post["title"], "og_url": post["url"],
                "published": post["date"],
                "jsonld": [
                    crumbs(site, ("Posts", f"{url}/posts/"), (post["title"], post["url"])),
                    {"@context": "https://schema.org", "@type": "BlogPosting", "headline": post["title"],
                     "description": post["description"], "datePublished": post["date"], "dateModified": post["updated"],
                     "url": post["url"], "mainEntityOfPage": post["url"], "image": f"{url}/assets/og.png",
                     "author": {"@type": "Organization", "name": site["name"], "url": f"{url}/"},
                     "publisher": {"@type": "Organization", "name": site["name"],
                                   "logo": {"@type": "ImageObject", "url": f"{url}/assets/icon-512.png"}}},
                ],
            },
        )

    # archive
    desc = "Every Bunker Scale post and rating, newest first."
    render(
        "archive.html", "posts/index.html", nav="posts", has_subscribe=True,
        head={
            "title": f"All posts | {site['name']}", "description": desc, "canonical": f"{url}/posts/",
            "og_title": "All posts", "og_url": f"{url}/posts/",
            "jsonld": [crumbs(site, ("Posts", f"{url}/posts/")),
                       {"@context": "https://schema.org", "@type": "CollectionPage", "name": "All posts", "url": f"{url}/posts/"}],
        },
    )

    # static pages
    for name, page in pages.items():
        purl = f"{url}{page['path']}"
        ld = []
        if page.get("breadcrumb"):
            ld.append(crumbs(site, (page["breadcrumb"], purl)))
        if page.get("schema_type"):
            ld.append({"@context": "https://schema.org", "@type": page["schema_type"], "name": page["title"],
                       "url": purl, "description": page["description"]})
        render(
            "page.html", f"{name}/index.html", nav=page.get("nav", ""), has_subscribe=bool(page.get("subscribe")),
            page=page,
            head={"title": f"{page['title']} | {site['name']}", "description": page["description"],
                  "canonical": purl, "og_title": page["title"], "og_url": purl, "jsonld": ld},
        )

    # ratings board and the ignore pile
    render(
        "ratings.html", "ratings/index.html", nav="ratings", has_subscribe=True,
        head={
            "title": f"Ratings | {site['name']}",
            "description": "The current overall Bunker Scale reading, every rating so far, and every rating change, with the reasons.",
            "canonical": f"{url}/ratings/", "og_title": "Ratings", "og_url": f"{url}/ratings/",
            "jsonld": [crumbs(site, ("Ratings", f"{url}/ratings/"))],
        },
    )
    render(
        "ignore.html", "ignore/index.html", nav="", has_subscribe=True,
        head={
            "title": f"What You Can Probably Ignore | {site['name']}",
            "description": "The scariest-sounding AI claims from recent headlines, and why each one is less than it sounds.",
            "canonical": f"{url}/ignore/", "og_title": "What You Can Probably Ignore", "og_url": f"{url}/ignore/",
            "jsonld": [crumbs(site, ("What You Can Probably Ignore", f"{url}/ignore/"))],
        },
    )

    render(
        "404.html", "404.html", nav="", has_subscribe=False,
        head={"title": f"Page not found | {site['name']}", "description": "This page does not exist.",
              "canonical": None, "og_title": "Page not found", "og_url": f"{url}/404.html", "jsonld": []},
    )

    # feeds, sitemap, llms.txt
    for name in ("rss.xml", "feed.xml"):
        write(ROOT / name, rss(site, posts, name), changed, dry)
    write(ROOT / "sitemap.xml", sitemap(site, posts, pages), changed, dry)
    write(ROOT / "llms.txt", env.get_template("llms.txt").render(**common, pages=pages), changed, dry)
    return changed


def current_reading(site: dict) -> dict | None:
    cr = site.get("current_reading")
    if not cr:
        return None
    value = int(cr["value"])
    as_of = as_date(cr["as_of"])
    history = []
    for h in site.get("reading_history") or []:
        hd = as_date(h["date"])
        history.append({"date": hd.isoformat(), "date_long": long_date(hd), "value": int(h["value"]),
                        "band": band_for(site["bands"], int(h["value"])), "note": str(h.get("note", ""))})
    return {"value": value, "band": band_for(site["bands"], value), "as_of": as_of.isoformat(),
            "as_of_long": long_date(as_of), "direction": cr.get("direction"),
            "summary": str(cr.get("summary", "")).strip(), "deg": needle_deg(value), "history": history}


def rss(site: dict, posts: list[dict], self_name: str) -> str:
    url = site["url"]

    def stamp(p):
        return format_datetime(dt.datetime.combine(p["date_obj"], dt.time(13, 0), tzinfo=dt.timezone.utc))

    items = []
    for p in posts:
        content = absolute_urls(p["body_html"], url).replace("]]>", "]]]]><![CDATA[>")
        items.append(
            f"<item><title>{esc(p['title'])}</title><link>{p['url']}</link>"
            f'<guid isPermaLink="true">{p["url"]}</guid><pubDate>{stamp(p)}</pubDate>'
            f"<description>{esc(p['description'])}</description>"
            f"<content:encoded><![CDATA[{content}]]></content:encoded></item>"
        )
    newest = stamp(posts[0]) if posts else format_datetime(dt.datetime.now(dt.timezone.utc))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<?xml-stylesheet type="text/css" href="/rss.css"?>\n'
        '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">\n'
        f"<channel><title>{esc(site['name'])}</title><link>{url}/</link><description>{esc(site['description'])}</description>"
        f"<language>en-us</language><lastBuildDate>{newest}</lastBuildDate>\n"
        f'<atom:link href="{url}/{self_name}" rel="self" type="application/rss+xml"/>'
        f"<image><url>{url}/assets/icon-512.png</url><title>{esc(site['name'])}</title><link>{url}/</link></image>\n"
        + "".join(items)
        + "</channel></rss>\n"
    )


def sitemap(site: dict, posts: list[dict], pages: dict) -> str:
    url = site["url"]
    newest = max((p["updated"] for p in posts), default=dt.date.today().isoformat())
    locs = [(f"{url}/", newest)]
    locs += [(f"{url}{pages[n]['path']}", newest) for n in ("about", "how-the-ratings-work")]
    locs += [(f"{url}/posts/", newest), (f"{url}/ratings/", newest), (f"{url}/ignore/", newest),
             (f"{url}/privacy/", newest)]
    locs += [(p["url"], p["updated"]) for p in posts]
    rows = "\n".join(f"<url><loc>{loc}</loc><lastmod>{mod}</lastmod></url>" for loc, mod in locs)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"{rows}\n</urlset>\n")


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate and list changes without writing")
    ap.add_argument("--reimport-from", metavar="REV", help="re-import post/page HTML edited directly since REV")
    ap.add_argument("--no-adopt", action="store_true", help="skip importing stray post HTML")
    args = ap.parse_args()

    if not args.no_adopt and not args.check:
        for note in adopt_stray_html(args.reimport_from):
            print(f"safety net: {note}")

    site = load_site()
    posts = load_posts(site)
    pages = load_pages()

    problems, warnings = validate.check(site, posts, REQUIRED_SECTIONS)
    for w in warnings:
        print(f"warning: {w}")
    if problems:
        for p in problems:
            print(f"ERROR: {p}")
        print(f"\n{len(problems)} problem(s). Nothing was published. Fix the source file(s) above and try again.")
        return 1

    changed = build(site, posts, pages, dry=args.check)
    link_problems = validate.check_links(ROOT)
    for p in link_problems:
        print(f"ERROR: {p}")
    verb = "would change" if args.check else "changed"
    print(f"{len(posts)} posts. {len(changed)} file(s) {verb}" + (":" if changed else "."))
    for c in changed:
        print(f"  {c}")
    return 1 if link_problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
