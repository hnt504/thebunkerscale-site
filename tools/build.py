#!/usr/bin/env python3
"""Build The Bunker Scale from source.

Source of truth:
  site.yml               site-wide settings, the scale bands, the current reading
  content/posts/*.md     posts (Markdown, or .html for posts imported from the old site)
  content/pages/*.html   About, How the Ratings Work, Privacy
  templates/*.html       page layouts (Jinja2)

Everything else at the repo root (index.html, posts/, rss.xml, sitemap.xml ...)
is generated by this script. Don't edit generated files by hand: the next build
overwrites them.

Usage:
  python3 tools/build.py                 validate, then build
  python3 tools/build.py --check         validate and report what would change, write nothing
  python3 tools/build.py --reimport-from <git-rev>
                                         first pull in post/page HTML that a bot
                                         edited directly since <git-rev>
"""

from __future__ import annotations

